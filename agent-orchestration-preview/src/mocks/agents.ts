/** 读取 Agent 列表 */
export const getAgents = async (): Promise<ApiResponse<AgentConfig[]>> => {
  await delay();
  return ok(clone(AGENTS));
};

/** 读取 Agent 运行记录 */
export const getAgentRuns = async (): Promise<ApiResponse<AgentRun[]>> => {
  await delay();
  return ok(clone(AGENT_RUNS));
};

/** 按 id 读取单个 Agent */
export const getAgentById = (id: string): AgentConfig | undefined =>
  AGENTS.find((a) => a.agent_id === id);
